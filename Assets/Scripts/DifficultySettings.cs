using UnityEngine;

// Настройки сложности одним файлом-ассетом (ScriptableObject). Два готовых: Assets/Resources/Difficulty/Normal
// (казуальная, по умолчанию) и Challenge (как было до фидбэка). Крутить числа можно прямо в Inspector, в том числе
// во время Play. Новый набор: правой кнопкой в Project -> Create -> Astral Shinobi -> Difficulty Settings.
//
// Какой набор действует на уровне: поле Difficulty у компонента LevelManager (объект LevelManager в сцене уровня).
// Пусто - берётся Normal. Читается через Difficulty.Current.
[CreateAssetMenu(menuName = "Astral Shinobi/Difficulty Settings", fileName = "NewDifficulty")]
public class DifficultySettings : ScriptableObject
{
    [Header("Враги")]
    [Tooltip("Множитель скорости ВСЕХ врагов (мечник, кунайщик, лучник) к их maxSpeed из префаба/сцены. 1 = как в префабе (4.25), 0.8 = на 20% медленнее. Применяется один раз, когда враг появляется на уровне.")]
    [Range(0.3f, 2f)] public float enemySpeedMultiplier = 1f;

    [Tooltip("Сколько секунд враг замедляется после попадания ножом (0 = выключено). Помогает понять, что нож попал.")]
    [Min(0f)] public float hitStunDuration = 0f;

    [Tooltip("Во сколько раз от обычной скорости враг идёт, пока замедлен после попадания: 0 = стоит на месте, 0.2 = почти стоит, 1 = без замедления.")]
    [Range(0f, 1f)] public float hitStunSpeedFactor = 0.2f;

    [Tooltip("Скорость полёта куная кунайщика, юнитов в секунду. Было 10 в префабе (на Level_4 стояло 17). Чем меньше, тем легче увернуться.")]
    [Min(1f)] public float enemyKunaiSpeed = 17f;

    [Tooltip("Скорость полёта стрелы лучника, юнитов в секунду (было 20).")]
    [Min(1f)] public float enemyArrowSpeed = 20f;

    [Header("Нож")]
    [Tooltip("Множитель скорости полёта ножа к Speed из префаба Knife (18). 1.4 = на 40% быстрее.")]
    [Range(0.5f, 3f)] public float knifeSpeedMultiplier = 1f;

    [Tooltip("Множитель размера ножа (спрайт и острие): больше нож - легче его видеть.")]
    [Range(0.5f, 2.5f)] public float knifeScaleMultiplier = 1f;

    [Tooltip("Невидимый запас вокруг врага для попадания ножом (юниты): нож засчитывается как попавший, если пролетел не дальше этого расстояния от тела врага. 0 - только настоящее касание, 0.15 - попадание, даже когда нож прошёл в миллиметре. Враг ≈ 1 юнит.")]
    [Min(0f)] public float knifeEnemyHitPadding = 0f;

    [Tooltip("Сколько раз нож отскакивает от стен, прежде чем исчезнуть (было 3).")]
    [Min(0)] public int knifeMaxBounces = 3;

    [Tooltip("ВКЛ: красных линий нет, бросок валиден под любым углом (даже вплотную к стене), траектория всегда жёлтая. ВЫКЛ: как раньше - бросок слишком близко к стене или в угол блокируется красной линией.")]
    public bool allowAnyThrowAngle = false;

    [Tooltip("Урон ножа по числу отскоков ДО попадания во врага: 1-й элемент - прямое попадание (0 отскоков), 2-й - после 1 отскока, 3-й - после 2, и т.д. Если отскоков больше, чем элементов, берётся последний. Хп врага по умолчанию 100. Было: 20 / 40 / 60 / 80.")]
    public float[] knifeDamageByBounces = { 20f, 40f, 60f, 80f };

    [Tooltip("Траектория при прицеливании: сколько участков показывать и насколько каждый непрозрачен (0 = невидим, 1 = полностью). Первый элемент - прямой участок, второй - после первого отскока, третий - после второго (до 4 участков). Например 0.9 / 0.6 / 0.3: каждый следующий бледнее предыдущего.")]
    public float[] trajectoryLegAlphas = { 0.5f, 0.5f };

    [Tooltip("Отражает ли нож игрока вражеские кунаи и стрелы (физически отталкивает их). ВЫКЛ (по умолчанию): снаряды врагов пролетают сквозь нож, и в руке, и в полёте. ВКЛ - возможная будущая фича: коллайдер ножа включён.")]
    public bool knifeDeflectsEnemyProjectiles = false;

    [Tooltip("ВКЛ: если игрок стоит вплотную к стене (ближе длины ножа) и целится в неё, траектория НЕ рисуется и бросок запрещён. Работает невидимым конусом перед игроком. ВЫКЛ: бросать можно всегда (нож у самой стены сразу отскочит).")]
    public bool blockFlushThrows = false;

    [Tooltip("Половина угла невидимого конуса запрета броска у стены, градусов: стена в пределах ±этого угла от направления прицела тоже считается «вплотную». Больше = запрет срабатывает и при прицеливании под углом к стене.")]
    [Range(0f, 60f)] public float flushConeHalfAngle = 15f;

    [Tooltip("ЭКСПЕРИМЕНТ: если нож сделал ВСЕ возможные отскоки (Knife Max Bounces) и после этого попал во врага - враг умирает сразу, независимо от хп.")]
    public bool oneShotAfterAllBounces = false;

    [Tooltip("Радиус поимки ножа вокруг игрока (юниты): кнопка загорается, когда отскочивший нож внутри этого радиуса. Нож ловится по нажатию кнопки.")]
    [Min(0.5f)] public float catchRadius = 1.4f;

    [Tooltip("Окно прощения поимки, секунд (реальное время): нож можно поймать ещё столько времени после того, как он был в радиусе поимки. Нож быстрый и успевает выйти из радиуса за время тапа по кнопке; без окна нажатие в такой момент отказывало, хотя кнопка была активна.")]
    [Min(0f)] public float catchGraceTime = 0.4f;

    [Header("Парирование")]
    [Tooltip("Угол парирования, градусов: ширина конуса перед игроком, в который должен попасть враг, чтобы удар можно было парировать. Игрок смотрит в центр конуса; враг в пределах половины угла в каждую сторону от взгляда - парирование включается. 360 = со всех сторон, 100 = как было (±50°).")]
    [Range(10f, 360f)] public float parryConeAngle = 100f;

    [Tooltip("Сколько секунд занимает один проход шарика по дуге. Больше = медленнее ползунок = проще.")]
    [Min(0.1f)] public float parryPassDuration = 0.5f;

    [Tooltip("Замедление шарика к центру дуги и ускорение к краям. 0 - равномерное движение (как раньше), 0.5 - у краёв шарик ≈ в 4 раза быстрее, чем в центре, 1 - в самом центре почти замирает. Время прохода (parryPassDuration) не меняется: меняется только распределение скорости.")]
    [Range(0f, 0.95f)] public float parryCenterSlowdown = 0f;

    [Tooltip("Сколько проходов делает шарик (туда, обратно, опять туда = 3).")]
    [Range(1, 8)] public int parryPasses = 3;

    [Tooltip("Половина ширины окна парирования в долях дуги (0.06 = 6% в обе стороны от центра квадратика). Больше = квадратик больше = проще.")]
    [Range(0.01f, 0.3f)] public float parryTargetHalfWidth = 0.06f;

    [Tooltip("Высота зелёной цели в долях длины дуги (поперёк дуги). Ширина вдоль дуги задаётся окном парирования, так что цель становится прямоугольником: шире, но не выше. 0 = квадрат (высота = ширине). Для сравнения: 0.12 примерно как квадрат со стороной в окно 0.06.")]
    [Range(0f, 0.3f)] public float parryTargetHeight = 0f;

    [Tooltip("Запас на границе квадратика, в долях дуги: тап засчитывается, если ЦЕНТР шарика не дальше (полуширина + этот запас) от центра квадратика. Это «кружок на границе квадратика»: шарик касается края - уже успех.")]
    [Range(0f, 0.1f)] public float parryEdgeTolerance = 0f;

    [Tooltip("Кулдаун парирования после мини-игры, секунд.")]
    [Min(0f)] public float parryCooldown = 5f;

    [Tooltip("Во сколько раз быстрее бежит шарик за КАЖДОГО дополнительного мечника, ударившего в ту же итерацию (множится). 1 = без ускорения.")]
    [Min(1f)] public float parrySpeedPerExtraAttacker = 1.5f;

    [Header("Замедление при прицеливании")]
    [Tooltip("Во сколько раз замедляется время, пока игрок целится (0.1 = почти стоп).")]
    [Range(0.02f, 1f)] public float aimTimeScale = 0.1f;

    [Tooltip("Сколько реальных секунд держится полное замедление с начала прицеливания.")]
    [Min(0f)] public float aimSlowDuration = 2f;

    [Tooltip("Изначальный размер камеры (Orthographic Size): сколько юнитов видно по высоте / 2. 5 = видно 10 юнитов по высоте. На этом масштабе завязаны радиусы, скорости и сетка A*: меняй осторожно. Отдаление колесом мыши и при прицеливании считается от этого значения.")]
    [Range(2f, 12f)] public float cameraSize = 5f;

    [Tooltip("ЭКСПЕРИМЕНТ «режим обзора»: отдельный стик с глазиком слева от стика прицеливания. Пока палец на нём - время стоит, экран затемнён, траектории нет, а камера смещается от игрока в сторону стика. Выключено - стика и режима нет.")]
    public bool aimLookEnabled = false;

    [Tooltip("Насколько далеко камера может сместиться от игрока в режиме обзора (юниты), когда стик с глазиком отклонён до упора.")]
    [Range(0f, 15f)] public float aimLookPanRadius = 3f;

    [Tooltip("ЭКСПЕРИМЕНТ: при прицеливании камера отдаляется по мере отведения стика прицела от центра, до этого множителя (2 = размер камеры вдвое больше при стике на краю). 1 = отдаления нет.")]
    [Range(1f, 3f)] public float aimUnzoomMax = 2f;

    [Tooltip("За сколько реальных секунд время возвращается к норме после этого.")]
    [Min(0.05f)] public float aimRecoverDuration = 1f;

    // Урон ножа при данном числе отскоков до попадания (0 = прямое попадание).
    public float DamageForBounces(int bounces)
    {
        if (knifeDamageByBounces == null || knifeDamageByBounces.Length == 0) return 20f;
        return knifeDamageByBounces[Mathf.Clamp(bounces, 0, knifeDamageByBounces.Length - 1)];
    }
}
